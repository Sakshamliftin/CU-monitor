from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime


def _format_uptime(seconds: int) -> str:
    """Convert total seconds to a human-readable string like ``5d 03:12:15``."""
    days, remainder = divmod(seconds, 86400)
    hours, remainder = divmod(remainder, 3600)
    minutes, secs = divmod(remainder, 60)
    if days > 0:
        return f"{days}d {hours:02d}:{minutes:02d}:{secs:02d}"
    return f"{hours:02d}:{minutes:02d}:{secs:02d}"


@dataclass
class RNState:
    """
    Snapshot of a Radio Node's current state.
    """
    rn_id: str
    cu_id: str
    cu_name: str
    rn_name: str
    ip: str
    pci: int = 0
    uptime_seconds: int = 0
    node_state: str = "UNKNOWN"  # OOS, REBOOTED, HEALTHY, UNKNOWN
    last_seen: str = ""
    reboot_count: int = 0

    @property
    def uptime_display(self) -> str:
        return _format_uptime(self.uptime_seconds)

    def to_dict(self) -> dict:
        return {
            "rn_id": self.rn_id,
            "cu_id": self.cu_id,
            "cu_name": self.cu_name,
            "rn_name": self.rn_name,
            "ip": self.ip,
            "pci": self.pci,
            "uptime_seconds": self.uptime_seconds,
            "uptime_display": self.uptime_display,
            "node_state": self.node_state,
            "last_seen": self.last_seen,
            "reboot_count": self.reboot_count,
        }


@dataclass
class MonitoringEvent:
    """
    A monitoring event generated by the system (e.g. reboot detected).
    """
    event_type: str
    cu_name: str
    rn_name: str
    timestamp: str = ""
    details: str = ""

    def to_dict(self) -> dict:
        return {
            "event_type": self.event_type,
            "cu_name": self.cu_name,
            "rn_name": self.rn_name,
            "timestamp": self.timestamp,
            "details": self.details,
        }
